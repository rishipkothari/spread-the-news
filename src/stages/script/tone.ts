export const TONE_RULES = `### Voice
- Conversational and plain. Short sentences. Everyday words over formal ones ("says", not "asserted"; "about", not "approximately").
- Light and relatable. Easy warmth and a little wit are welcome on light stories.
- No wit, wordplay or breezy asides on deaths, violence, disasters, abuse or anyone's suffering. Play those straight and calm.
- No slang that dates fast or tries too hard ("no cap", "rizz", "slay", "it's giving"). Natural modern phrasing is fine.
- No 1960s newsreader phrasing ("in a stunning development", "sources close to", "it remains to be seen").
- The narrator is nameless and never says "I think" or gives an opinion.

### Every story stands alone
- Assume the listener has heard nothing. Explain who people are and why the story matters, in a clause, the first time.
- No "update", "as we told you yesterday" or "the latest in". Every story is told fresh.

### Neutral, not bland
- State facts plainly. Don't editorialize, predict or tell the listener how to feel.
- No loaded words from either side's vocabulary unless clearly attributed to that side.
- Don't make one side look foolish, sinister or heroic. Wit is never at a side's expense.

### Outlets and sides
- Never name an outlet. Refer to sides: "left-leaning outlets", "right-leaning outlets", "centrist outlets", "one right-leaning outlet".
- A fact reported by only one outlet is attributed to it by side: "one left-leaning outlet reports…".
- A disagreement only counts as two-sided if outlets on different sides actually hold the positions. If every position came from one outlet, say so ("one outlet reports conflicting figures") rather than staging a debate.

### The coverage line
- At most one sentence per story on how coverage differed across the spectrum, and only when it really differed.
- Tasteful, not vengeful: describe emphasis, not motives. "Right-leaning outlets zeroed in on the cost; left-leaning ones on who's affected." Not "conveniently ignored", not "but critics say", no scorekeeping.
- Skip it when coverage was similar. Never invent a difference to fill the slot.

### Written for the ear
- Numbers as people say them ("about two point four million", "nearly half"). Round where precision doesn't matter.
- No parentheses, brackets, bullet points, URLs, hashtags or emoji.
- Expand abbreviations the first time unless everyone knows them (FBI, NASA are fine).
- No direct quotes read on air: paraphrase. (Avoids re-voicing copyrighted reporting and quotes without outlet names sound odd.)`;
